test('令和→西暦', () => { assert.equal(reiwaToIso('令和８年５月１日'), '2026-05-01'); assert.equal(reiwaToIso('令和８年３月31 日'), '2026-03-31'); });

test('訂正事務連絡: 表紙の別添→対象通知、区分番号/施設基準/その他の訂正レコード', () => {
  const r = parseTeisei(doc);
  assert.equal(r.date, '2026-05-01');
  assert.deepEqual(r.targets.map(t => [t.n, t.title]), [[1, '診療報酬の算定方法の一部改正に伴う実施上の留意事項について'], [2, '基本診療料の施設基準等及びその届出に関する手続きの取扱いについて'], [3, '歯科の診療録及び診療報酬明細書に使用できる略称について']]);
  const codes = r.records.map(x => [x.kind, x.code]);
  assert.deepEqual(codes, [['kubun', '医:A104'], ['kubun', '医:A215'], ['kubun', '調:00'], ['other', null], ['shisetsu', '施:機能強化加算'], ['other', null]]);
  assert.match(r.records[0].text, /病棟の管理栄養士/);
  assert.equal(r.records[0].besshi, 1);
  assert.equal(r.records[4].target, '基本診療料の施設基準等及びその届出に関する手続きの取扱いについて');
  assert.match(r.records[5].text, /歯ＤＸ１/);
});
